    fun getTrendingVideos(category: String): List<VideoItem> {
        if (category == "All" || category.isBlank()) {
            return ALL_VIDEOS
        }
        val filtered = ALL_VIDEOS.filter { it.category.equals(category, ignoreCase = true) }
        return if (filtered.isNotEmpty()) filtered else ALL_VIDEOS
    }

    fun searchCurated(query: String): List<VideoItem> {
        val q = query.trim().lowercase()
        return ALL_VIDEOS.filter {
            it.title.lowercase().contains(q) ||
            it.channelTitle.lowercase().contains(q) ||
            it.description.lowercase().contains(q) ||
            it.category.lowercase().contains(q)
        }
    }

    fun getRelatedVideos(currentVideoId: String): List<VideoItem> {
        return ALL_VIDEOS.filter { it.id != currentVideoId }.take(8)
